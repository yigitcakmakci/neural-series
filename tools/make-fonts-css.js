"use strict";
// Writes assets\fonts\fonts.css and assets\fonts\editor-fonts.css from the @fontsource packages in node_modules:
// the latin and latin-ext subsets (latin-ext carries Turkish ğ ş İ) of the weights the apps use, WOFF2 only.
// build.ps1 copies every file these style sheets name into each app's fonts\ folder.
//   node tools\make-fonts-css.js
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SUBSETS = ["latin-ext", "latin"];
const SHEETS = {
  // all five apps
  "fonts.css": [
    { pkg: "chakra-petch", weights: [400, 500, 600, 700], italic: [400, 500, 700] },
    { pkg: "rajdhani", weights: [500, 600, 700] },
    { pkg: "share-tech-mono", weights: [400] }, // latin only: ğ ş İ come from the fallback fonts
  ],
  // NeuralPad's editor font menu
  "editor-fonts.css": [
    { pkg: "ibm-plex-mono", weights: [400, 500, 700], italic: [400, 500, 700] },
    { pkg: "jetbrains-mono", weights: [400, 500, 700], italic: [400, 500, 700] },
    { pkg: "space-mono", weights: [400, 700], italic: [400, 700] },
    { pkg: "oxanium", weights: [400, 700] },
  ],
};

for (const [sheet, families] of Object.entries(SHEETS)) {
  const out = [`/* Generated by tools/make-fonts-css.js from @fontsource packages; SIL Open Font License 1.1 (see *-OFL.txt). */`];
  for (const f of families) {
    const dir = path.join(ROOT, "node_modules", "@fontsource", f.pkg);
    const version = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8")).version;
    out.push("", `/* ${f.pkg} ${version} */`);
    const styles = [...f.weights.map((w) => [w, "normal"]), ...(f.italic || []).map((w) => [w, "italic"])];
    for (const [weight, style] of styles) {
      const css = fs.readFileSync(path.join(dir, `${weight}${style === "italic" ? "-italic" : ""}.css`), "utf8");
      for (const subset of SUBSETS) {
        const name = `${f.pkg}-${subset}-${weight}-${style}`;
        const block = css.split("@font-face").find((b) => b.includes(`${name}.woff2`));
        if (!block && subset === "latin-ext" && f.pkg === "share-tech-mono") continue;
        if (!block) throw new Error(`no @font-face for ${name}`);
        const family = /font-family:\s*'([^']+)'/.exec(block)[1];
        const range = /unicode-range:\s*([^;]+);/.exec(block)[1];
        if (!fs.existsSync(path.join(dir, "files", `${name}.woff2`))) throw new Error(`missing ${name}.woff2`);
        out.push(`@font-face { font-family: "${family}"; font-style: ${style}; font-weight: ${weight}; font-display: swap;`,
          `  src: url("${name}.woff2") format("woff2");`,
          `  unicode-range: ${range}; }`);
      }
    }
  }
  const file = path.join(ROOT, "assets", "fonts", sheet);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, out.join("\n") + "\n");
  const faces = out.filter((l) => l.startsWith("@font-face")).length;
  console.log(`${path.relative(ROOT, file)}: ${faces} faces`);
}
